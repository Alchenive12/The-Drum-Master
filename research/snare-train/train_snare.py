# File: research/snare-train/train_snare.py
#
# Fine-tunes the shipped hit classifier (HitClassifierWeights.h) so it recognises real snares (and
# keeps every other type), then compares old vs new on sample packs it never trained on and on the
# acoustic / electronic regression sets from research/classifier-train.
#
# Runs on the user's PC: the inputs are feature rows from oneshot_extract.cpp (numbers, not audio).
# Starting from the shipped weights (and pulling towards them, "L2-SP") keeps what the network
# learned from Groove / E-GMD, which can't be downloaded here; synthetic loops are mixed in as a
# rehearsal set.
#
# Usage: python3 train_snare.py <work_dir> <old_header> <out_header> --name full|clean
#            [--train-packs all|<pack;pack>] [--test-packs <pack;pack>] [--extra-train X_snsyn.csv]
# <work_dir> holds list.tsv, feat/os_*.csv, feat/mix_*.csv, X_syn.csv, X_ac.csv, X_el.csv.
import glob, os, re, sys, time
import numpy as np

TYPES = ["kick", "snare", "closedHat", "openHat", "crash", "ride", "rimshot", "clap", "misc"]
MISC = 8
MELS, SEGS = 32, 7
CUT = 0.45   # HitClassifier: primary = most likely non-misc type if >= 0.55 - 0.2 * sensitivity (50 %)

def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default

# ------------------------------------------------------------------ weights in / out
def load_header(path):
    rows = [l for l in open(path) if l.strip().startswith("{{")]
    vals = [np.array([float(v.rstrip("f")) for v in re.findall(r"-?[\d.]+(?:e[-+]?\d+)?f", r)], dtype=np.float64) for r in rows]
    mean, scale, w1, b1, w2, b2 = vals
    H = len(b1)
    return dict(mean=mean, scale=scale, w1=w1.reshape(len(mean), H), b1=b1, w2=w2.reshape(H, len(b2)), b2=b2)

def write_header(path, P, comment_lines):
    fl = lambda a: ", ".join(f"{float(v):.6g}f" for v in np.ravel(a))
    H = len(P["b1"])
    with open(path, "w") as f:
        f.write("// File: dsp/include/plugin_dsp/HitClassifierWeights.h\n")
        f.write("// GENERATED by research/snare-train/train_snare.py - do not edit by hand.\n")
        f.write("// Weights of the hit classifier network (HitClassifier.h, decision D-C1).\n")
        for c in comment_lines: f.write("// " + c + "\n")
        f.write("#pragma once\n\n#include \"TinyMlp.h\"\n\n#include <cstddef>\n\nnamespace plugin_dsp\n{\n")
        f.write(f"constexpr std::size_t hitClassifierHidden = {H};\n\n")
        f.write(f"inline const TinyMlpWeights<{len(P['mean'])}, {H}, {len(P['b2'])}>& hitClassifierWeights()\n{{\n")
        f.write(f"    static const TinyMlpWeights<{len(P['mean'])}, {H}, {len(P['b2'])}> w {{\n")
        rows = [P["mean"], P["scale"], P["w1"], P["b1"], P["w2"], P["b2"]]
        for i, a in enumerate(rows):
            f.write("        {{ " + fl(a) + " }}" + ("," if i + 1 < len(rows) else "") + "\n")
        f.write("    };\n    return w;\n}\n} // namespace plugin_dsp\n")

def forward(P, X):
    Xn = (X - P["mean"]) * P["scale"]
    h = np.maximum(0.0, Xn @ P["w1"] + P["b1"])
    return 1.0 / (1.0 + np.exp(-np.clip(h @ P["w2"] + P["b2"], -30, 30)))

def primary(p):
    best = p[:, :MISC].argmax(1)
    return np.where(p[:, :MISC].max(1) >= CUT, best, MISC)

# ------------------------------------------------------------------ data
def read_csv(path):
    cache = path + ".npy"
    if os.path.exists(cache) and os.path.getmtime(cache) >= os.path.getmtime(path):
        return np.load(cache)
    with open(path) as f: ncol = len(f.readline().split(","))
    d = np.loadtxt(path, delimiter=",", skiprows=1, ndmin=2, dtype=np.float64, usecols=range(ncol))
    np.save(cache, d)
    return d

def cut(X):
    """--use-extra k: keep the first k extra 10 ms segments of longer-window features (k=0: the plugin's 40 ms)."""
    k = arg("--use-extra")
    if k is None: return X
    keep = 224 + 32 * int(k)
    return np.hstack([X[:, :keep], X[:, -1:]]) if X.shape[1] - 1 > keep else X

def load_set(path, with_files=False):
    """extract.cpp CSV: file, onset, 9 labels, 225 features -> X, y (, file per row)"""
    with open(path) as f:
        ncol = len(f.readline().split(","))
        files = np.array([line.split(",", 1)[0] for line in f])
    d = np.loadtxt(path, delimiter=",", skiprows=1, usecols=range(2, ncol), dtype=np.float64, ndmin=2)
    return (cut(d[:, 9:]), d[:, :9].astype(np.int8), files) if with_files else (cut(d[:, 9:]), d[:, :9].astype(np.int8))

def halves(X, y, files):
    """Split a loop set by track: first half guards training (model selection), second half reports."""
    u = np.unique(files); g = np.isin(files, u[::2])
    return (X[g], y[g]), (X[~g], y[~g])

def augment(X, rng):
    """Random static EQ + level in the feature domain (same as research/classifier-train/train.py)."""
    n = len(X)
    m = np.linspace(-1, 1, MELS)[None, :]
    curve = rng.uniform(-6, 6, (n, 1)) * m
    for _ in range(2):
        c = rng.uniform(-1, 1, (n, 1)); w = rng.uniform(0.1, 0.4, (n, 1)); g = rng.uniform(-6, 6, (n, 1))
        curve += g * np.exp(-0.5 * ((m - c) / w) ** 2)
    segs = (X.shape[1] - 1) // MELS                      # 7, or more with a longer listening window
    rel = X[:, :-1].reshape(n, segs, MELS) + curve[:, None, :]
    shift = rel[:, 1:SEGS, :].reshape(n, -1).max(1)     # level reference: the original 0-40 ms segments
    out = np.empty_like(X)
    out[:, :-1] = np.maximum(rel - shift[:, None, None], -80.0).reshape(n, -1)
    out[:, -1] = X[:, -1] + shift + rng.uniform(-12, 6, n)
    return out

# ------------------------------------------------------------------ scoring
def oneshot_table(name, P, X, det, truth, groups, sel):
    """Like drum_bench --oneshots: share of tests labelled right, missed detections count as wrong."""
    p = forward(P, X[sel]); pr = primary(p); ok = (pr == truth[sel]) & (det[sel] == 1)
    out = {}
    for g in sorted(set(groups[sel])):
        m = groups[sel] == g
        out[g] = (ok[m].mean() * 100, int(m.sum()) // 3)
    out["ALL"] = (ok.mean() * 100, int(sel.sum()) // 3)
    return out, pr

def f1_report(P, X, y):
    pred = (forward(P, X) >= 0.5).astype(int)
    f1 = []
    for t in range(9):
        if y[:, t].sum() == 0: f1.append(np.nan); continue
        tp = ((pred[:, t] == 1) & (y[:, t] == 1)).sum(); fp = ((pred[:, t] == 1) & (y[:, t] == 0)).sum(); fn = ((pred[:, t] == 0) & (y[:, t] == 1)).sum()
        f1.append(2 * tp / max(1, 2 * tp + fp + fn))
    return np.array(f1)

def beat_score(P, X, y):
    """Plugin decision on onsets inside beats. score = mean of the per-class rates, minus false snares."""
    pr = primary(forward(P, X)); n = y.sum(1)
    snare = y[:, 1] == 1
    clap = (y[:, 7] == 1) & ~snare
    hat = (y[:, 2] == 1) & (n == 1)
    kick = (y[:, 0] == 1) & (n == 1)
    nons = (n >= 1) & (y[:, 1] == 0) & (y[:, 6] == 0) & (y[:, 7] == 0)
    r = lambda m, ok: float(ok[m].mean() * 100) if m.sum() else float("nan")
    out = {"snare": r(snare, pr == 1), "clap": r(clap, pr == 7), "hat": r(hat, pr == 2), "kick": r(kick, pr == 0),
           "false_snare": r(nons, pr == 1)}
    vals = [out[k] for k in ("snare", "clap", "hat", "kick") if not np.isnan(out[k])]
    out["score"] = (np.mean(vals) - 2 * np.nan_to_num(out["false_snare"])) / 100
    return out

# ------------------------------------------------------------------ training
def train(P0, Xtr, ytr, wtr, Xva, va_fn, rng, epochs=40, lam=float(arg('--lam', '3e-3')), lr=float(arg('--lr', '3e-4')), batch=256):
    P = {k: v.copy() for k, v in P0.items()}
    heads = [int(t) for t in arg("--heads").split(",")] if arg("--heads") else None
    keys = ["w1", "b1", "w2", "b2"]
    m = {k: np.zeros_like(P[k]) for k in keys}; v = {k: np.zeros_like(P[k]) for k in keys}
    step = 0; best = (va_fn(P0), {k: x.copy() for k, x in P0.items()}, 0)
    print(f"  epoch  0  validation {best[0]:.3f} (the shipped network)", flush=True)
    for ep in range(epochs):
        Xa = augment(Xtr, rng)
        Xa[:, -1] += rng.uniform(-18, 6, len(Xa))
        order = rng.permutation(len(Xa))
        for s in range(0, len(order), batch):
            idx = order[s:s + batch]
            Xn = (Xa[idx] - P["mean"]) * P["scale"]
            a1 = Xn @ P["w1"] + P["b1"]; h = np.maximum(0.0, a1)
            p = 1.0 / (1.0 + np.exp(-np.clip(h @ P["w2"] + P["b2"], -30, 30)))
            g2 = (p - ytr[idx]) * wtr[idx][:, None] / len(idx)            # d BCE / d logit
            grads = {"w2": h.T @ g2, "b2": g2.sum(0)}
            gh = (g2 @ P["w2"].T) * (a1 > 0)
            grads["w1"] = Xn.T @ gh; grads["b1"] = gh.sum(0)
            if heads is not None:                                         # only retrain these outputs
                grads["w1"][:] = 0; grads["b1"][:] = 0
                off = [t for t in range(P["b2"].shape[0]) if t not in heads]
                grads["w2"][:, off] = 0; grads["b2"][off] = 0
            step += 1
            for k in keys:
                g = grads[k] + lam * (P[k] - P0[k])                           # L2-SP: stay near the shipped net
                m[k] = 0.9 * m[k] + 0.1 * g; v[k] = 0.999 * v[k] + 0.001 * g * g
                P[k] -= lr * (m[k] / (1 - 0.9 ** step)) / (np.sqrt(v[k] / (1 - 0.999 ** step)) + 1e-8)
                if heads is not None and k in ("w1", "b1"): P[k] = P0[k].copy()
                if heads is not None and k in ("w2", "b2"):
                    off = [t for t in range(P["b2"].shape[0]) if t not in heads]
                    if k == "w2": P[k][:, off] = P0[k][:, off]
                    else: P[k][off] = P0[k][off]
        score = va_fn(P)
        print(f"  epoch {ep + 1:2d}  validation {score:.3f}", flush=True)
        if score > best[0]: best = (score, {k: x.copy() for k, x in P.items()}, ep + 1)
        elif ep + 1 - best[2] >= 6: break
    print(f"  best epoch {best[2]} (validation {best[0]:.3f})")
    return best[1]

def main():
    W, old_h, out_h = sys.argv[1], sys.argv[2], sys.argv[3]
    name = arg("--name", "full")
    rng = np.random.default_rng(int(arg("--seed", "0")))
    P0 = load_header(old_h)
    widen = int(arg("--widen", "0"))
    if widen:   # extra hidden units: random inputs, zero outputs, so the network starts out unchanged
        r = np.random.default_rng(7)
        P0["w1"] = np.hstack([P0["w1"], r.normal(0, 0.05, (P0["w1"].shape[0], widen))])
        P0["b1"] = np.concatenate([P0["b1"], np.zeros(widen)])
        P0["w2"] = np.vstack([P0["w2"], np.zeros((widen, P0["w2"].shape[1]))])

    items = [l.rstrip("\n").split("\t") for l in open(f"{W}/list.tsv", encoding="utf-8", errors="surrogateescape")]
    pack = np.array([it[1] for it in items]); group = np.array([it[2] for it in items]); typ = np.array([int(it[3]) for it in items])
    FD = arg("--feat", "feat"); SX = arg("--sets-suffix", "")
    os_rows = np.vstack([read_csv(f) for f in sorted(glob.glob(f"{W}/{FD}/os_*.csv"))])
    mix_rows = np.vstack([read_csv(f) for f in sorted(glob.glob(f"{W}/{FD}/mix_*.csv"))])
    idx = os_rows[:, 0].astype(int); det = os_rows[:, 3].astype(int); y_os = os_rows[:, 4:13].astype(np.int8); X_os = cut(os_rows[:, 13:])
    keep = os_rows[:, 2] > 0                                                   # drop unreadable files
    idx, det, y_os, X_os = idx[keep], det[keep], y_os[keep], X_os[keep]
    g_os = group[idx]; t_os = typ[idx]; p_os = pack[idx]
    extra_in = X_os.shape[1] - len(P0["mean"])
    if extra_in > 0:   # longer listening window: new feature blocks start with zero weight (net unchanged)
        ref = X_os[det == 1]; at = len(P0["mean"]) - 1                       # insert before the level feature
        P0["mean"] = np.concatenate([P0["mean"][:at], ref[:, at:at + extra_in].mean(0), P0["mean"][at:]])
        P0["scale"] = np.concatenate([P0["scale"][:at], 1.0 / (ref[:, at:at + extra_in].std(0) + 1e-3), P0["scale"][at:]])
        P0["w1"] = np.vstack([P0["w1"][:at], np.zeros((extra_in, P0["w1"].shape[1])), P0["w1"][at:]])
        print(f"   listening window: {extra_in} extra features (zero-initialised)")
    bfiles = sorted(glob.glob(f"{W}/{FD}/beat_*.csv"))
    bt_rows = np.vstack([read_csv(f) for f in bfiles]) if bfiles else np.zeros((0, os_rows.shape[1]))
    bi, y_bt, X_bt = bt_rows[:, 0].astype(int), bt_rows[:, 4:13].astype(np.int8), cut(bt_rows[:, 13:])
    mi, mj, mdet, y_mx, X_mx = mix_rows[:, 0].astype(int), mix_rows[:, 1].astype(int), mix_rows[:, 3].astype(int), mix_rows[:, 4:13].astype(np.int8), cut(mix_rows[:, 13:])

    test_packs = set(arg("--test-packs", "").split(";")) - {""}
    tp = arg("--train-packs", "all")
    train_packs = (set(pack) - test_packs) if tp == "all" else (set(tp.split(";")) - {""})
    is_test = np.array([p in test_packs for p in p_os]); is_train = np.array([p in train_packs for p in p_os])
    mx_test = np.array([pack[a] in test_packs and pack[b] in test_packs for a, b in zip(mi, mj)])
    mx_train = np.array([pack[a] in train_packs and pack[b] in train_packs for a, b in zip(mi, mj)])
    bt_test = np.array([pack[a] in test_packs for a in bi], dtype=bool)
    bt_train = np.array([pack[a] in train_packs for a in bi], dtype=bool)
    bt_va = bt_train & (bi % 8 == 0)                       # 1 kit in 8 checks training (validation)
    bt_fit = bt_train & ~bt_va
    print(f"== {name}: {len(train_packs)} training packs, {len(test_packs)} test packs")
    print("   training packs:", "; ".join(sorted(train_packs)) or "(none)")
    print("   test packs:    ", "; ".join(sorted(test_packs)))

    # validation: 12 % of the training sounds (by sound, all 3 velocities together)
    tr_sounds = np.unique(idx[is_train]); rng.shuffle(tr_sounds)
    va_sounds = set(tr_sounds[: len(tr_sounds) * 12 // 100])
    is_va = np.array([i in va_sounds for i in idx]) & is_train
    if not train_packs:   # clean model: nothing from the packs is trained on; they only pick the epoch
        is_va = ~is_test
    is_fit = is_train & ~is_va & (det == 1)

    Xs, ys = load_set(f"{W}/X_syn{SX}.csv")
    (gaX, gay), (raX, ray) = halves(*load_set(f"{W}/X_ac{SX}.csv", True))
    (geX, gey), (reX, rey) = halves(*load_set(f"{W}/X_el{SX}.csv", True))
    guard_sets = lambda P: np.array([np.nanmean(f1_report(P, gaX, gay)), np.nanmean(f1_report(P, geX, gey))])
    g0 = guard_sets(P0)
    guard0 = 0.0
    guard = lambda P: float(np.minimum(0.0, guard_sets(P) - g0).sum())   # each loop set on its own may not get worse
    parts_X = [X_os[is_fit], X_mx[mx_train & (mdet == 1)], X_bt[bt_fit], Xs]
    parts_y = [y_os[is_fit], y_mx[mx_train & (mdet == 1)], y_bt[bt_fit], ys]
    extra = arg("--extra-train")
    if extra:
        Xe_, ye_ = load_set(extra); parts_X.append(Xe_); parts_y.append(ye_)
    Xtr = np.vstack(parts_X); ytr = np.vstack(parts_y).astype(np.float64)
    counts = ytr.sum(0) + 1; target = np.median(counts)
    wtr = np.ones(len(ytr))
    wtr[len(ytr) - len(ys) - (len(ye_) if extra else 0): len(ytr) - (len(ye_) if extra else 0)] = float(arg("--synth-weight", "0.3"))
    for t in range(9):
        if counts[t] < target: wtr[ytr[:, t] == 1] = np.maximum(wtr[ytr[:, t] == 1], min(8.0, target / counts[t]))
    for spec in arg("--boost", "").split(","):          # e.g. --boost 2:2 = closed hats count double
        if spec: t, fct = spec.split(":"); wtr[ytr[:, int(t)] == 1] *= float(fct)
    print("   training rows:", len(ytr), " labels:", dict(zip(TYPES, ytr.sum(0).astype(int))))

    def va_fn(P):   # mean per-type accuracy on validation sounds (plugin decision rule)
        sel = is_va
        acc = 0.0
        if sel.sum():
            pr = primary(forward(P, X_os[sel])); ok = (pr == t_os[sel]) & (det[sel] == 1)
            acc = float(np.mean([ok[t_os[sel] == t].mean() for t in np.unique(t_os[sel])]))
        if bt_va.sum() and float(arg("--beat-weight", "1")) > 0:
            acc = (acc + float(arg("--beat-weight", "1")) * beat_score(P, X_bt[bt_va], y_bt[bt_va])["score"]) / (1 + float(arg("--beat-weight", "1")))
        drop = min(0.0, guard(P) - guard0 + float(arg('--slack', '0.0')))   # real loops may not get worse
        return acc + float(arg('--guard-weight', '10')) * drop

    t0 = time.time()
    P = train(P0, Xtr, ytr, wtr, None, va_fn, rng, epochs=int(arg("--epochs", "40")))
    print(f"   trained in {time.time() - t0:.0f} s")

    # ---------------- results
    res = []
    if not test_packs:   # final model on every pack: nothing left to test on but the real loops
        is_test = is_va.copy(); test_packs = {"(validation sounds from the training packs)"}
    old, _ = oneshot_table("old", P0, X_os, det, t_os, g_os, is_test)
    new, _ = oneshot_table("new", P, X_os, det, t_os, g_os, is_test)
    res.append(f"ONE-SHOTS FROM PACKS IT NEVER TRAINED ON ({', '.join(sorted(test_packs))})")
    res.append("   (each sound alone at 3 velocities; plugin decision rule at sensitivity 50; missed = wrong)")
    res.append(f"   {'group':12} {'sounds':>6}   {'old':>6}   {'new':>6}")
    for g in sorted(old, key=lambda k: (k == 'ALL', k)):
        res.append(f"   {g:12} {old[g][1]:6d}   {old[g][0]:5.1f}%   {new[g][0]:5.1f}%")
    sn = is_test & (t_os == 1) & (det == 1)
    for label, PP in (("old", P0), ("new", P)):
        pr = primary(forward(PP, X_os[sn]))
        c = {TYPES[k]: int((pr == k).sum()) for k in range(9) if (pr == k).sum() > 0}
        res.append(f"   snares were labelled ({label}): {c}")
    if bt_test.sum() or not arg("--test-packs"):
        bsel = bt_test if bt_test.sum() else bt_va
        res.append(f"BEATS BUILT FROM {'THE TEST PACKS' if bt_test.sum() else 'VALIDATION KITS'} (2-bar beats, every onset; plugin decision rule)")
        for label, PP in (("old", P0), ("new", P)):
            b = beat_score(PP, X_bt[bsel], y_bt[bsel])
            res.append(f"   {label}: snare hits called snare {b['snare']:.1f}% | clap {b['clap']:.1f}% | hat-only onsets called hat {b['hat']:.1f}% | "
                       f"kick-only called kick {b['kick']:.1f}% | NON-snare onsets called snare {b['false_snare']:.1f}%  ({int(bsel.sum())} onsets)")
    sel = mx_test & (mdet == 1)
    if sel.sum():
        for label, PP in (("old", P0), ("new", P)):
            p = forward(PP, X_mx[sel]); yy = y_mx[sel]
            top = yy[:, [1, 6, 7]].argmax(1); topi = np.array([1, 6, 7])[top]
            got = p[np.arange(len(p)), topi] >= 0.5
            snm = yy[:, 1] == 1
            res.append(f"   layered hits ({label}): snare/clap/rim found under a kick or hat {got.mean() * 100:.1f}%  (snares {got[snm].mean() * 100:.1f}%, {int(sel.sum())} tests)")
    res.append("REGRESSION CHECK: real drum loops, tracks not used for model selection (per-type F1 at 0.5)")
    for nm, X, y in (("MDB acoustic", raX, ray), ("electronic loops", reX, rey)):
        for label, PP in (("old", P0), ("new", P)):
            f = f1_report(PP, X, y)
            res.append(f"   {nm:17} {label}: macro {np.nanmean(f):.2f} | " + " ".join(f"{TYPES[t][:6]}={'  - ' if np.isnan(f[t]) else f'{f[t]:.2f}'}" for t in range(9)))
    text = "\n".join(res)
    print(text)
    with open(out_h + ".results.txt", "w") as f: f.write(f"model: {name}\n" + text + "\n")

    snare_old, snare_new = old.get("snare", (0, 0))[0], new.get("snare", (0, 0))[0]
    comments = [
        f"Variant: {name.upper()}. Fine-tuned from the Groove / E-GMD weights (CC BY 4.0, Magenta) with research/snare-train.",
        "Fine-tuning data: " + ("; ".join(sorted(train_packs)) if train_packs else "none from sample packs") + " + own synthetic loops"
        + (" + " + os.path.basename(extra) if extra else "") + ".",
        f"Test set ({'; '.join(sorted(test_packs))[:120]}): snare {snare_old:.0f}% -> {snare_new:.0f}%, all types {old['ALL'][0]:.0f}% -> {new['ALL'][0]:.0f}% (one-shots, 3 velocities).",
    ]
    if arg("--note"): comments.append(arg("--note"))
    if name == "full":
        comments.append("FULL variant: trained on commercial sample packs - for personal use, not for release (see docs/08).")
    write_header(out_h, P, comments)
    print("wrote", out_h)

if __name__ == "__main__":
    main()
