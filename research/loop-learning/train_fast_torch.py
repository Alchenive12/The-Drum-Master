# File: research/loop-learning/train_fast_torch.py
#
# Fine-tunes the plugin's live (fast, 40 ms) hit classifier on the GPU, from extract_long.cpp CSVs, which
# already carry the plugin's own 225-number picture ("f" columns) and labels for every detected onset.
# Starts from the current main network (dsp/include/plugin_dsp/HitClassifierWeights.h) and pulls towards it
# (L2-SP), like research/snare-train/train_snare.py, but can now rehearse on Groove / E-GMD (acoustic) next
# to the owner's packs, so live acoustic drums need not get worse while producer drums improve.
#
# Scoring emulates HitClassifier exactly: main network, then the second (V1) network per-type max with
# "main leads above 0.6" (HitClassifier::runNetworks), then eval.cpp's weights/score (loop_learning.py).
# --check verifies the emulation against the plugin probabilities stored in each CSV.
#
# Usage: python train_fast_torch.py --train a.csv b.csv@2 ... --test t1.csv ... --main <HitClassifierWeights.h>
#            --v1 <HitClassifierWeightsV1.h> --out <new header> [--lam 1e-3] [--epochs 30] [--lr 3e-4]
import argparse, os, re, sys, time
import numpy as np
import torch
from torch import nn

import loop_learning as L

def load_header(path):
    rows = [l for l in open(path) if l.strip().startswith("{{")]
    vals = [np.array([float(v.rstrip("f")) for v in re.findall(r"-?[\d.]+(?:e[-+]?\d+)?f", r)], dtype=np.float64) for r in rows]
    mean, scale, w1, b1, w2, b2 = vals
    H = len(b1)
    return dict(mean=mean, scale=scale, w1=w1.reshape(len(mean), H), b1=b1, w2=w2.reshape(H, len(b2)), b2=b2)

def write_header(path, P, comment):
    fl = lambda a: ", ".join(f"{float(v):.6g}f" for v in np.ravel(a))
    H = len(P["b1"]); I = len(P["mean"]); O = len(P["b2"])
    with open(path, "w") as f:
        f.write("// File: dsp/include/plugin_dsp/HitClassifierWeights.h\n")
        f.write("// GENERATED by research/loop-learning/train_fast_torch.py - do not edit by hand.\n")
        f.write("// Weights of the hit classifier network (HitClassifier.h, decision D-C1).\n")
        for c in comment: f.write("// " + c + "\n")
        f.write("#pragma once\n\n#include \"TinyMlp.h\"\n\n#include <cstddef>\n\nnamespace plugin_dsp\n{\n")
        f.write(f"constexpr std::size_t hitClassifierHidden = {H};\n\n")
        f.write(f"inline const TinyMlpWeights<{I}, {H}, {O}>& hitClassifierWeights()\n{{\n")
        f.write(f"    static const TinyMlpWeights<{I}, {H}, {O}> w {{\n")
        rows = [P["mean"], P["scale"], P["w1"], P["b1"], P["w2"], P["b2"]]
        for i, a in enumerate(rows):
            f.write("        {{ " + fl(a) + " }}" + ("," if i + 1 < len(rows) else "") + "\n")
        f.write("    };\n    return w;\n}\n} // namespace plugin_dsp\n")

def mlp(P, F):
    h = np.maximum(((F - P["mean"]) * P["scale"]) @ P["w1"] + P["b1"], 0.0)
    return 1.0 / (1.0 + np.exp(-(h @ P["w2"] + P["b2"])))

def combine(pm, pv, lead=0.6):
    """HitClassifier::runNetworks: per-type max with V1; the main net's top type leads above `lead`."""
    p = np.maximum(pm, pv)
    nm = pm.copy(); nm[:, 8] = -1.0
    top = nm[:, :8].argmax(1)
    topP = pm[np.arange(len(pm)), top]
    lead_rows = topP >= lead
    capped = np.minimum(p, (topP - 0.01)[:, None])
    keep = np.zeros_like(p, dtype=bool); keep[np.arange(len(p)), top] = True
    return np.where(lead_rows[:, None] & ~keep, capped, p)

class Net(nn.Module):
    def __init__(self, P, dev):
        super().__init__()
        t = lambda a: torch.tensor(a, dtype=torch.float32, device=dev)
        self.mean, self.scale = t(P["mean"]), t(P["scale"])
        self.w1, self.b1 = nn.Parameter(t(P["w1"])), nn.Parameter(t(P["b1"]))
        self.w2, self.b2 = nn.Parameter(t(P["w2"])), nn.Parameter(t(P["b2"]))
        self.ref = [t(P[k]) for k in ("w1", "b1", "w2", "b2")]
    def forward(self, x):
        return torch.relu(((x - self.mean) * self.scale) @ self.w1 + self.b1) @ self.w2 + self.b2
    def l2sp(self):
        return sum(((p - r) ** 2).sum() for p, r in zip((self.w1, self.b1, self.w2, self.b2), self.ref))
    def export(self, P):
        Q = dict(P)
        for k, p in zip(("w1", "b1", "w2", "b2"), (self.w1, self.b1, self.w2, self.b2)): Q[k] = p.detach().cpu().numpy().astype(np.float64)
        return Q

def augment(F, rng):
    """train.py's static EQ + level augmentation, for the 225-number layout (32 mels x 7 segments + level)."""
    MELS, SEGS = 32, 7
    n = len(F)
    m = np.linspace(-1, 1, MELS)[None, :]
    curve = rng.uniform(-6, 6, (n, 1)) * m
    for _ in range(2):
        c = rng.uniform(-1, 1, (n, 1)); w = rng.uniform(0.1, 0.4, (n, 1)); g = rng.uniform(-6, 6, (n, 1))
        curve += g * np.exp(-0.5 * ((m - c) / w) ** 2)
    out = F.copy()
    rel = F[:, :SEGS * MELS].reshape(n, SEGS, MELS) + curve[:, None, :]
    shift = rel[:, 1:, :].reshape(n, -1).max(1)
    out[:, :SEGS * MELS] = np.maximum(rel - shift[:, None, None], -80.0).reshape(n, -1)
    out[:, SEGS * MELS] = F[:, SEGS * MELS] + shift + rng.uniform(-12, 6, n)
    return out.astype(np.float32)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train", nargs="+", required=True)
    ap.add_argument("--test", nargs="*", default=[])
    ap.add_argument("--main", required=True)
    ap.add_argument("--v1", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lam", type=float, default=1e-3)
    ap.add_argument("--lr", type=float, default=3e-4)
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--aug", type=int, default=1)
    ap.add_argument("--max-rows", type=int, default=2000000)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    torch.manual_seed(a.seed); rng = np.random.default_rng(a.seed)
    P0, V1 = load_header(a.main), load_header(a.v1)

    tests = [(os.path.splitext(os.path.basename(p))[0], L.load(p)) for p in a.test]
    if a.check:
        for name, d in tests:
            P = combine(mlp(P0, d["F"]), mlp(V1, d["F"]))
            print(f"check {name}: max |emulated - plugin| = {np.abs(P - d['P']).max():.2e}", flush=True)

    Fs, Ys, Ws, files = [], [], [], []
    for spec in a.train:
        p, _, wt = spec.partition("@")
        d = L.load(p)
        Fs.append(d["F"]); Ys.append(d["Y"]); Ws.append(np.full(len(d["F"]), float(wt or 1)))
        files.append(np.array([os.path.basename(p) + "|" + f for f in d["file"]]))
        print(f"train {os.path.basename(p)}: {len(d['F'])} hits x{wt or 1}", flush=True)
    F, Y, W, files = np.vstack(Fs).astype(np.float32), np.vstack(Ys).astype(np.float32), np.concatenate(Ws), np.concatenate(files)
    if len(F) > a.max_rows:
        k = rng.choice(len(F), a.max_rows, replace=False); F, Y, W, files = F[k], Y[k], W[k], files[k]
    # validation: 8 % of the training FILES (loops / performances), never rows of a file seen in training
    uf = np.unique(files); rng.shuffle(uf); vfiles = set(uf[: max(1, len(uf) * 8 // 100)])
    isv = np.array([f in vfiles for f in files])
    Fv, Yv = F[isv], Y[isv]
    F, Y, W = F[~isv], Y[~isv], W[~isv]
    idx = np.repeat(np.arange(len(F)), np.round(W).astype(int))
    F, Y = F[idx], Y[idx]
    if a.aug > 0:
        F = np.vstack([F] + [augment(F, rng) for _ in range(a.aug)]); Y = np.vstack([Y] * (a.aug + 1))
    print(f"training rows {len(F)}, validation rows {len(Fv)}, on {dev}", flush=True)

    net = Net(P0, dev)
    opt = torch.optim.Adam([net.w1, net.b1, net.w2, net.b2], lr=a.lr)
    lossf = nn.BCEWithLogitsLoss()
    Ft, Yt = torch.from_numpy(F).pin_memory() if dev == "cuda" else torch.from_numpy(F), torch.from_numpy(Y)
    Fvt, Yvt = torch.from_numpy(Fv).to(dev), torch.from_numpy(Yv).to(dev)
    def vloss():
        with torch.no_grad(): return lossf(net(Fvt), Yvt).item()
    best, bestQ, wait, t0 = vloss(), net.export(P0), 0, time.time()
    print(f"start: validation loss {best:.4f}", flush=True)
    for ep in range(a.epochs):
        order = torch.randperm(len(Ft))
        for b in range(0, len(order), 1024):
            i = order[b:b + 1024]
            xb, yb = Ft[i].to(dev, non_blocking=True), Yt[i].to(dev, non_blocking=True)
            opt.zero_grad()
            (lossf(net(xb), yb) + a.lam * net.l2sp() / len(F) * 1024).backward()
            opt.step()
        v = vloss()
        print(f"epoch {ep + 1} validation loss {v:.4f} ({time.time() - t0:.0f} s)", flush=True)
        if v < best - 1e-5: best, bestQ, wait = v, net.export(P0), 0
        else:
            wait += 1
            if wait >= 5: break

    print(f"\nper-type F1 (precision): before -> after   [plugin rule: main + V1 max, main leads above 0.6]")
    for name, d in tests:
        before = combine(mlp(P0, d["F"]), mlp(V1, d["F"]))
        after = combine(mlp(bestQ, d["F"]), mlp(V1, d["F"]))
        fb, pb, n = L.score(L.weights(before), d); fa, pa, _ = L.score(L.weights(after), d)
        print(f"{name:16s}" + "".join(f"  {L.TYPES[t][:6]} {fb[t]:.2f}->{fa[t]:.2f} ({pa[t]:.2f})" for t in range(8) if n[t]), flush=True)
    write_header(a.out, bestQ, [f"Fine-tuned from {os.path.basename(a.main)} on: " + " ".join(os.path.basename(s) for s in a.train),
                                "FULL variant: trained on commercial sample packs - personal use only, do not ship (docs/08)."])
    np.savez(os.path.splitext(a.out)[0] + ".npz", **{k: v for k, v in bestQ.items()})
    print("saved", a.out)

if __name__ == "__main__":
    main()
