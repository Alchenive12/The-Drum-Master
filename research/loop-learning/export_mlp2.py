# File: research/loop-learning/export_mlp2.py
# Writes a two-hidden-layer network trained by train_slow_torch.py --picture F (the plugin's own 225-number
# picture) as dsp/include/plugin_dsp/HitClassifierWeights.h for TinyMlp2 (TinyMlp.h).
# With --check <test.csv>, recomputes the network from the exported tables and compares it with the
# probabilities the trainer saved for that set (P_<name> in the .npz).
# Usage: python export_mlp2.py <model.npz> <out.h> [--second-net] [--note "..."] [--check test.csv ...]
import argparse, os
import numpy as np

def tables(z):
    ws = sorted({k.split(".")[0] for k in z.files if k.endswith(".weight")}, key=int)
    if len(ws) != 3: raise SystemExit(f"expected 3 linear layers, found {ws}")
    W = [z[f"{i}.weight"].T.astype(np.float32) for i in ws]   # torch (out, in) -> row-major [in][out]
    B = [z[f"{i}.bias"].astype(np.float32) for i in ws]
    return z["mean"].astype(np.float32), (1.0 / z["std"]).astype(np.float32), W, B

def forward(F, mean, scale, W, B):
    h = np.maximum(((F - mean) * scale) @ W[0] + B[0], 0)
    h = np.maximum(h @ W[1] + B[1], 0)
    return 1 / (1 + np.exp(-np.clip(h @ W[2] + B[2], -30, 30)))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model"); ap.add_argument("out")
    ap.add_argument("--second-net", action="store_true", help="keep running the V1 network next to it (per-type max)")
    ap.add_argument("--note", default="")
    ap.add_argument("--check", nargs="*", default=[])
    a = ap.parse_args()
    z = np.load(a.model)
    mean, scale, W, B = tables(z)
    I, H1, H2, O = W[0].shape[0], W[0].shape[1], W[1].shape[1], W[2].shape[1]
    def fl(arr):
        v = [f"{float(x):.7g}f" for x in np.ravel(arr)]
        return "\n    " + ",\n    ".join(",".join(v[i:i + 16]) for i in range(0, len(v), 16)) + "\n"
    with open(a.out, "w", newline="\n") as f:
        f.write("// File: dsp/include/plugin_dsp/HitClassifierWeights.h\n")
        f.write("// GENERATED by research/loop-learning/export_mlp2.py - do not edit by hand.\n")
        f.write(f"// Main hit-classifier network: {I} -> {H1} ReLU -> {H2} ReLU -> {O} sigmoid (TinyMlp2).\n")
        if a.note: f.write(f"// {a.note}\n")
        f.write("#pragma once\n\n#include \"TinyMlp.h\"\n\n#include <cstddef>\n\nnamespace plugin_dsp\n{\n")
        f.write(f"using HitClassifierMainNet = TinyMlp2<{I}, {H1}, {H2}, {O}>;\n")
        f.write(f"constexpr bool hitClassifierSecondNetDefault = {'true' if a.second_net else 'false'};\n\n")
        f.write("namespace hit_classifier_tables\n{\n")
        for name, arr in [("mean", mean), ("scale", scale), ("w1", W[0]), ("b1", B[0]), ("w2", W[1]), ("b2", B[1]), ("w3", W[2]), ("b3", B[2])]:
            f.write(f"alignas (16) inline const float {name}[{arr.size}] = {{{fl(arr)}}};\n")
        f.write("} // namespace hit_classifier_tables\n\n")
        f.write("inline const TinyMlp2Weights& hitClassifierWeights()\n{\n    namespace t = hit_classifier_tables;\n")
        f.write("    static const TinyMlp2Weights w { t::mean, t::scale, t::w1, t::b1, t::w2, t::b2, t::w3, t::b3 };\n    return w;\n}\n")
        f.write("} // namespace plugin_dsp\n")
    print(f"wrote {a.out}: {I}-{H1}-{H2}-{O}, {sum(w.size for w in W)} weights, {os.path.getsize(a.out) / 1e6:.1f} MB")
    if a.check:
        import loop_learning as L
        for p in a.check:
            name = os.path.splitext(os.path.basename(p))[0]
            d = L.load(p)
            err = np.abs(forward(d["F"], mean, scale, W, B) - z["P_" + name]).max()
            print(f"check {name}: max |exported - trained| = {err:.2e}")

if __name__ == "__main__":
    main()
