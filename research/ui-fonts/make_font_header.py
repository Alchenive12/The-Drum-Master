#!/usr/bin/env python3
# File: research/ui-fonts/make_font_header.py
# Builds Source/ui/FontData.h: the editor's typefaces as byte arrays, so the UI stays header-only
# (no CMakeLists / BinaryData change). All three families are SIL Open Font License 1.1 with no
# Reserved Font Name, so subsetting them is allowed; their licences are copied next to the header
# (Source/ui/fonts/) and credited on the About page.
#
#   Instrument Serif  (display: titles, drum names)  - Regular + Italic
#   Geist             (interface: labels, buttons)   - variable, instanced at 400 and 600
#   Geist Mono        (values and readouts)          - variable, instanced at 500
#
# needs: pip install fonttools
# usage: python3 research/ui-fonts/make_font_header.py   (from the repo root)
import io
import os
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/"
OUT_HEADER = "Source/ui/FontData.h"
OUT_LICENCES = "Source/ui/fonts"

# Latin, Latin-1 (± × ° ·), dashes, quotes, bullet, ellipsis, arrows, minus
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212]

FONTS = [  # (C++ name, file in google/fonts, weight for variable fonts or None)
    ("displayRegular", "instrumentserif/InstrumentSerif-Regular.ttf", None),
    ("displayItalic", "instrumentserif/InstrumentSerif-Italic.ttf", None),
    ("sansRegular", "geist/Geist%5Bwght%5D.ttf", 400),
    ("sansSemiBold", "geist/Geist%5Bwght%5D.ttf", 600),
    ("monoMedium", "geistmono/GeistMono%5Bwght%5D.ttf", 500),
]
LICENCES = [("instrumentserif/OFL.txt", "InstrumentSerif-OFL.txt"), ("geist/OFL.txt", "Geist-OFL.txt"),
            ("geistmono/OFL.txt", "GeistMono-OFL.txt")]


def fetch(path):
    with urllib.request.urlopen(BASE + path) as r:
        return r.read()


def build(data, weight):
    font = TTFont(io.BytesIO(data))
    if weight is not None:
        font = instancer.instantiateVariableFont(font, {"wght": weight}, updateFontNames=False)
    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "calt", "tnum", "lnum"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.hinting = False            # JUCE renders unhinted outlines
    s = subset.Subsetter(opts)
    s.populate(unicodes=UNICODES)
    s.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def main():
    cache = {}
    parts = []
    for name, path, weight in FONTS:
        if path not in cache:
            cache[path] = fetch(path)
        blob = build(cache[path], weight)
        rows = []
        for i in range(0, len(blob), 24):
            rows.append("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        parts.append(f"inline constexpr unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n")
        print(f"{name}: {len(blob)} bytes")

    with open(OUT_HEADER, "w", newline="\n") as f:
        f.write("// File: Source/ui/FontData.h\n")
        f.write("// GENERATED by research/ui-fonts/make_font_header.py - do not edit by hand.\n")
        f.write("// Instrument Serif (Copyright 2022 The Instrument Serif Project Authors), Geist and Geist Mono\n")
        f.write("// (Copyright 2024 The Geist Project Authors): SIL Open Font License 1.1, see Source/ui/fonts/.\n")
        f.write("// Latin subsets; Geist instanced at fixed weights.\n")
        f.write("#pragma once\n\nnamespace ui::fontdata\n{\n")
        f.write("\n".join(parts))
        f.write("} // namespace ui::fontdata\n")

    os.makedirs(OUT_LICENCES, exist_ok=True)
    for src, dst in LICENCES:
        with open(os.path.join(OUT_LICENCES, dst), "wb") as f:
            f.write(fetch(src))


if __name__ == "__main__":
    main()
