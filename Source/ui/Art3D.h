// File: Source/ui/Art3D.h
// The rendered 3D art (assets/ui3d, made by assets3d/scripts/*.py) and how it is drawn:
//   - the stage background in three lamp levels, crossfaded for the flicker, cached at the window's
//     real pixel size so each frame is a plain image copy;
//   - the knob filmstrip (64 positions, 8x8 grid, transparent with its own shadow);
//   - the brass plaque buttons (off / hover / on), drawn in three slices so the screws never stretch;
//   - the quick-mix panel.
// Every draw function returns false if its image is missing, so the code-drawn art in Art.h / Theme.h
// stays as the fallback.
#pragma once

#include <juce_gui_basics/juce_gui_basics.h>
#include <array>

#include "DrumMasterArt.h"   // generated by juce_add_binary_data (CMakeLists.txt)

namespace ui::art3d
{
inline juce::Image fromMemory (const char* data, int size) { return juce::ImageCache::getFromMemory (data, size); }

/** 0 = lamp at 15 %, 1 = 50 %, 2 = 100 %. The moonlight is the same in all three. */
inline juce::Image background (int level)
{
    switch (level)
    {
        case 0:  return fromMemory (DrumMasterArt::stage_bg_lamp015_jpg, DrumMasterArt::stage_bg_lamp015_jpgSize);
        case 1:  return fromMemory (DrumMasterArt::stage_bg_lamp050_jpg, DrumMasterArt::stage_bg_lamp050_jpgSize);
        default: return fromMemory (DrumMasterArt::stage_bg_lamp100_jpg, DrumMasterArt::stage_bg_lamp100_jpgSize);
    }
}

inline juce::Image knobStrip()
{
    return fromMemory (DrumMasterArt::knob_filmstrip_64_png, DrumMasterArt::knob_filmstrip_64_pngSize);
}

/** 0 = off, 1 = hover, 2 = on / pressed. */
inline juce::Image plaque (int state)
{
    switch (state)
    {
        case 1:  return fromMemory (DrumMasterArt::button_hover_2x_png, DrumMasterArt::button_hover_2x_pngSize);
        case 2:  return fromMemory (DrumMasterArt::button_on_2x_png, DrumMasterArt::button_on_2x_pngSize);
        default: return fromMemory (DrumMasterArt::button_off_2x_png, DrumMasterArt::button_off_2x_pngSize);
    }
}

inline juce::Image panel() { return fromMemory (DrumMasterArt::panel_2x_png, DrumMasterArt::panel_2x_pngSize); }

// -------------------------------------------------------------------------------- stage background
/** Keeps the three lamp levels rescaled to the size they are shown at, so a frame costs one image
    copy (two only during the short moments of a flicker). The cache grows up to the source size
    (2200 px wide) and only shrinks when the window gets much smaller, so zoom animations don't
    trigger a rescale on every frame. */
class StageBackground
{
public:
    bool isAvailable() const { return background (2).isValid(); }

    /** lamp: 1 = full warm light ... ~0.15 = the lamp almost out (the moon stays). */
    void draw (juce::Graphics& g, juce::Rectangle<float> area, float lamp)
    {
        const auto src = background (2);
        if (! src.isValid())
            return;
        const float physical = g.getInternalContext().getPhysicalPixelScaleFactor();
        const int wantW = juce::jlimit (64, src.getWidth(), juce::roundToInt (area.getWidth() * physical));
        if (cacheW == 0 || wantW > cacheW || wantW < cacheW / 2)
            rebuild (wantW, src);

        int lo = 1, hi = 2;
        float t = (lamp - 0.5f) / 0.5f;
        if (lamp < 0.5f) { lo = 0; hi = 1; t = (lamp - 0.15f) / 0.35f; }
        t = juce::jlimit (0.0f, 1.0f, t);

        g.setOpacity (1.0f);
        if (t >= 0.997f)
        {
            g.drawImage (levels[static_cast<std::size_t> (hi)], area);
            return;
        }
        g.drawImage (levels[static_cast<std::size_t> (lo)], area);
        if (t > 0.003f)
        {
            g.setOpacity (t);
            g.drawImage (levels[static_cast<std::size_t> (hi)], area);
            g.setOpacity (1.0f);
        }
    }

private:
    void rebuild (int w, const juce::Image& src)
    {
        const int h = juce::roundToInt (static_cast<float> (w) * static_cast<float> (src.getHeight()) / static_cast<float> (src.getWidth()));
        for (int k = 0; k < 3; ++k)
        {
            auto img = background (k);
            levels[static_cast<std::size_t> (k)] = img.getWidth() == w ? img : img.rescaled (w, h, juce::Graphics::highResamplingQuality);
        }
        cacheW = w;
    }

    std::array<juce::Image, 3> levels;
    int cacheW = 0;
};

// -------------------------------------------------------------------------------- knob
/** Draws the filmstrip frame for `proportion` (0..1) so the knob's body has radius bodyRadius. */
inline bool drawKnob (juce::Graphics& g, juce::Point<float> centre, float bodyRadius, float proportion, bool enabled)
{
    const auto strip = knobStrip();
    if (! strip.isValid())
        return false;
    constexpr int frames = 64, cols = 8;
    constexpr float bodyInFrame = 0.6f;              // knob diameter / frame width, from the render setup
    const int fs = strip.getWidth() / cols;
    const int idx = juce::jlimit (0, frames - 1, juce::roundToInt (proportion * static_cast<float> (frames - 1)));
    const float d = 2.0f * bodyRadius / bodyInFrame;
    const auto dest = juce::Rectangle<float> (d, d).withCentre (centre).getSmallestIntegerContainer();
    g.setOpacity (enabled ? 1.0f : 0.5f);
    g.drawImage (strip, dest.getX(), dest.getY(), dest.getWidth(), dest.getHeight(), (idx % cols) * fs, (idx / cols) * fs, fs, fs);
    g.setOpacity (1.0f);
    return true;
}

// -------------------------------------------------------------------------------- plaque buttons
/** Brass plaque in three slices: the screw ends keep their shape, only the middle stretches. */
inline bool drawPlaque (juce::Graphics& g, juce::Rectangle<float> r, int state)
{
    const auto img = plaque (state);
    if (! img.isValid())
        return false;
    const int iw = img.getWidth(), ih = img.getHeight();
    const int capSrc = juce::roundToInt (static_cast<float> (iw) * 0.12f);
    const auto ri = r.getSmallestIntegerContainer();
    const int capDst = juce::jmin (ri.getWidth() / 2, juce::roundToInt (static_cast<float> (ri.getHeight()) * static_cast<float> (capSrc) / static_cast<float> (ih)));
    const int mid = ri.getWidth() - 2 * capDst;
    g.setOpacity (1.0f);
    g.drawImage (img, ri.getX(), ri.getY(), capDst, ri.getHeight(), 0, 0, capSrc, ih);
    if (mid > 0)
        g.drawImage (img, ri.getX() + capDst, ri.getY(), mid, ri.getHeight(), capSrc, 0, iw - 2 * capSrc, ih);
    g.drawImage (img, ri.getRight() - capDst, ri.getY(), capDst, ri.getHeight(), iw - capSrc, 0, capSrc, ih);
    return true;
}

/** Any image stretched into an area (the quick-mix panel has the same aspect as its slot). */
inline bool drawImageIn (juce::Graphics& g, const juce::Image& img, juce::Rectangle<float> area)
{
    if (! img.isValid())
        return false;
    g.setOpacity (1.0f);
    g.drawImage (img, area);
    return true;
}
} // namespace ui::art3d
